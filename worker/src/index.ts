/**
 * Clicky Proxy Worker
 *
 * Proxies requests to Claude and ElevenLabs APIs so the app never
 * ships with raw API keys. Keys are stored as Cloudflare secrets.
 *
 * Routes:
 *   POST /chat              → Anthropic Messages API (streaming)
 *   POST /tts               → ElevenLabs TTS API
 *   POST /transcribe-token  → AssemblyAI short-lived streaming token
 *
 * Every request must carry the shared app token in the X-Clicky-App-Token
 * header. Without it, anyone who finds this Worker's URL could spend the
 * API credit behind these keys.
 */

interface Env {
  ANTHROPIC_API_KEY: string;
  ELEVENLABS_API_KEY: string;
  ELEVENLABS_VOICE_ID: string;
  ASSEMBLYAI_API_KEY: string;
  CLICKY_APP_TOKEN: string;
}

const APP_TOKEN_HEADER_NAME = "X-Clicky-App-Token";

/**
 * Compares two strings in constant time so the response timing does not
 * reveal how many leading characters of a guessed token were correct.
 */
function constantTimeStringsAreEqual(firstString: string, secondString: string): boolean {
  const encoder = new TextEncoder();
  const firstBytes = encoder.encode(firstString);
  const secondBytes = encoder.encode(secondString);
  if (firstBytes.length !== secondBytes.length) {
    return false;
  }
  let differenceAccumulator = 0;
  for (let byteIndex = 0; byteIndex < firstBytes.length; byteIndex++) {
    differenceAccumulator |= firstBytes[byteIndex]! ^ secondBytes[byteIndex]!;
  }
  return differenceAccumulator === 0;
}

/**
 * Returns true only when the Worker has an app token configured and the
 * request carries the same token. If the secret was never set, every
 * request is refused (fail closed) instead of leaving the proxy open.
 */
function requestCarriesValidAppToken(request: Request, env: Env): boolean {
  const configuredAppToken = env.CLICKY_APP_TOKEN;
  if (!configuredAppToken) {
    console.error("CLICKY_APP_TOKEN secret is not set; refusing all requests.");
    return false;
  }
  const providedAppToken = request.headers.get(APP_TOKEN_HEADER_NAME) ?? "";
  return constantTimeStringsAreEqual(providedAppToken, configuredAppToken);
}

export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    const url = new URL(request.url);

    if (request.method !== "POST") {
      return new Response("Method not allowed", { status: 405 });
    }

    if (!requestCarriesValidAppToken(request, env)) {
      return new Response("Unauthorized", { status: 401 });
    }

    try {
      if (url.pathname === "/chat") {
        return await handleChat(request, env);
      }

      if (url.pathname === "/tts") {
        return await handleTTS(request, env);
      }

      if (url.pathname === "/transcribe-token") {
        return await handleTranscribeToken(env);
      }
    } catch (error) {
      console.error(`[${url.pathname}] Unhandled error:`, error);
      return new Response(
        JSON.stringify({ error: String(error) }),
        { status: 500, headers: { "content-type": "application/json" } }
      );
    }

    return new Response("Not found", { status: 404 });
  },
};

async function handleChat(request: Request, env: Env): Promise<Response> {
  const body = await request.text();

  const response = await fetch("https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers: {
      "x-api-key": env.ANTHROPIC_API_KEY,
      "anthropic-version": "2023-06-01",
      "content-type": "application/json",
    },
    body,
  });

  if (!response.ok) {
    const errorBody = await response.text();
    console.error(`[/chat] Anthropic API error ${response.status}: ${errorBody}`);
    return new Response(errorBody, {
      status: response.status,
      headers: { "content-type": "application/json" },
    });
  }

  return new Response(response.body, {
    status: response.status,
    headers: {
      "content-type": response.headers.get("content-type") || "text/event-stream",
      "cache-control": "no-cache",
    },
  });
}

async function handleTranscribeToken(env: Env): Promise<Response> {
  const response = await fetch(
    "https://streaming.assemblyai.com/v3/token?expires_in_seconds=480",
    {
      method: "GET",
      headers: {
        authorization: env.ASSEMBLYAI_API_KEY,
      },
    }
  );

  if (!response.ok) {
    const errorBody = await response.text();
    console.error(`[/transcribe-token] AssemblyAI token error ${response.status}: ${errorBody}`);
    return new Response(errorBody, {
      status: response.status,
      headers: { "content-type": "application/json" },
    });
  }

  const data = await response.text();
  return new Response(data, {
    status: 200,
    headers: { "content-type": "application/json" },
  });
}

async function handleTTS(request: Request, env: Env): Promise<Response> {
  const body = await request.text();
  const voiceId = env.ELEVENLABS_VOICE_ID;

  const response = await fetch(
    `https://api.elevenlabs.io/v1/text-to-speech/${voiceId}`,
    {
      method: "POST",
      headers: {
        "xi-api-key": env.ELEVENLABS_API_KEY,
        "content-type": "application/json",
        accept: "audio/mpeg",
      },
      body,
    }
  );

  if (!response.ok) {
    const errorBody = await response.text();
    console.error(`[/tts] ElevenLabs API error ${response.status}: ${errorBody}`);
    return new Response(errorBody, {
      status: response.status,
      headers: { "content-type": "application/json" },
    });
  }

  return new Response(response.body, {
    status: response.status,
    headers: {
      "content-type": response.headers.get("content-type") || "audio/mpeg",
    },
  });
}
